package com.langfunda;

public class Identifiers3 {

	public static void main(String[] args) {

		float f = 123;
		float f1 = 1230;
		float f2 = 123.0f;
		float f3 = 0123.5f;
		float f4 = 0123;

		System.out.println(f);
		System.out.println(f1);
		System.out.println(f2);
		System.out.println(f3);
		System.out.println(f4);

	}

}
